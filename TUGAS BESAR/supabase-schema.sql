-- Jalankan sekali di Supabase > SQL Editor
create table if not exists public.telemetry (
  id bigint generated by default as identity primary key,
  device_id text not null default 'AW-001',
  aqi numeric not null,
  pm25 numeric not null,
  pm10 numeric not null,
  temperature numeric not null,
  humidity numeric not null,
  gas_raw integer,
  created_at timestamptz not null default now()
);
create index if not exists telemetry_created_at_idx on public.telemetry (created_at desc);
-- Akses tabel dilakukan server Vercel memakai service_role key; jangan taruh key itu di index.html atau firmware ESP32.
